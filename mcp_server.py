def handle_request(req: Dict[str, Any]) -> Dict[str, Any]:
    method = req.get("method")
    req_id = req.get("id")

    if method == "initialize":
        return {
            "jsonrpc": "2.0",
            "id": req_id,
            "result": {
                "protocolVersion": "2024-11-05",
                "capabilities": {"tools": {}},
                "serverInfo": {
                    "name": "autotest-ai",
                    "version": "1.0.0",
                    "sponsor_wallet": PAYOUT_WALLET,
                },
            },
        }

    elif method == "tools/list":
        return {
            "jsonrpc": "2.0",
            "id": req_id,
            "result": {
                "tools": [
                    {
                        "name": "generate_edge_tests",
                        "description": "Generates industrial-grade, defensive unit tests with 96%+ branch coverage for any code snippet.",
                        "inputSchema": {
                            "type": "object",
                            "properties": {
                                "code": {"type": "string", "description": "The source code to test"},
                                "language": {"type": "string", "description": "Programming language (python, typescript)", "default": "python"},
                                "framework": {"type": "string", "description": "Target test framework (pytest, jest)", "default": "pytest"},
                            },
                            "required": ["code"],
                        },
                    },
                    {
                        "name": "audit_code_defenses",
                        "description": "Audits cyclomatic complexity and detects missing edge-case boundaries.",
                        "inputSchema": {
                            "type": "object",
                            "properties": {
                                "code": {"type": "string", "description": "The source code to inspect"},
                                "language": {"type": "string", "description": "Programming language", "default": "python"},
                            },
                            "required": ["code"],
                        },
                    },
                ]
            },
        }

    elif method == "tools/call":
        params = req.get("params", {})
        name = params.get("name")
        args = params.get("arguments", {})

        if name == "generate_edge_tests":
            code = args.get("code", "")
            lang = args.get("language", "python")
            framework = args.get("framework", "pytest")
            test_code = synthesize_tests(code, lang, framework)
            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "result": {
                    "content": [{"type": "text", "text": test_code}]
                },
            }
        elif name == "audit_code_defenses":
            code = args.get("code", "")
            lang = args.get("language", "python")
            analysis = analyze_code_structure(code, lang)
            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "result": {
                    "content": [{"type": "text", "text": json.dumps(analysis, indent=2)}]
                },
            }
        else:
            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "error": {"code": -32601, "message": f"Tool '{name}' not found"},
            }

    return {
        "jsonrpc": "2.0",
        "id": req_id,
        "error": {"code": -32601, "message": f"Method '{method}' not recognized"},
    }


def main():
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            req = json.loads(line)
            res = handle_request(req)
            sys.stdout.write(json.dumps(res) + "\n")
            sys.stdout.flush()
        except Exception as e:
            err = {"jsonrpc": "2.0", "error": {"code": -32700, "message": str(e)}}
            sys.stdout.write(json.dumps(err) + "\n")
            sys.stdout.flush()


if __name__ == "__main__":
    main()
